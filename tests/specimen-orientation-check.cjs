const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const T = require('../artifacts/parts-3d/vendor/three.min.js');
const source = fs.readFileSync(require.resolve('../artifacts/parts-3d/viewer.js'), 'utf8');
const context = vm.createContext({});
vm.runInContext(source.slice(0,source.indexOf('(function(){')),context);
assert.equal(typeof context.applySpecimenScrollRotation, 'function', 'Scroll rotation must preserve the current orientation');
const scroll = p => new T.Quaternion().setFromEuler(new T.Euler(p*.45,p*1.9,-p*.12));
const initial = new T.Quaternion().setFromEuler(new T.Euler(.53,-.48,.015));
const previous = new T.Quaternion();
const orientation = initial.clone();
context.applySpecimenScrollRotation(orientation,previous,scroll(.3));
const drag = new T.Quaternion().setFromEuler(new T.Euler(.2,-.6,.1));
orientation.premultiply(drag);
const dragged = orientation.clone();
context.applySpecimenScrollRotation(orientation,previous,scroll(.3));
assert.ok(orientation.angleTo(dragged)<1e-7,'Same scroll position must preserve a manual drag');
context.applySpecimenScrollRotation(orientation,previous,scroll(.6));
const expected = initial.clone().multiply(scroll(.6)).premultiply(drag);
assert.ok(orientation.angleTo(expected)<1e-7,'Further scrolling must keep the manual rotation');
context.applySpecimenScrollRotation(orientation,previous,scroll(.3));
assert.ok(orientation.angleTo(dragged)<1e-7,'A scroll round trip must restore the dragged orientation');
console.log('Manual rotation continuity and scroll round-trip checks passed.');
